"""
The REAL-model smoke suite (owner's ruling, 2026-10-17).

These tests call real providers with real keys. They prove the one thing the
fakes never can: the engine works against the actual world. They are OUT of
the 110 baseline on purpose — run them by hand, with keys exported in YOUR
terminal, never stored in any file:

    export OPENAI_API_KEY=...        # and/or ANTHROPIC_API_KEY=...
    /opt/venv/nexus-ai-env/bin/python -m pytest tests/test_real_smoke.py --real -s

Asserts check SHAPE (events arrive, in order, billed) — never exact wording,
because a real model says whatever it says. The exception: grounded facts the
model can only know by using a tool (live3's code word). Each test also PRINTS
what the model really said (-s shows it live) and the whole run is written to
tests/REPORT-live.md, so the evidence outlives the terminal.

A failure here means provider / network / key / model-id first, our code
second — check REPORT-live.md and the printed error before blaming the engine.
Costs per full run: a few cents (mini/haiku-class models, short prompts).
"""
from __future__ import annotations

import time
from pathlib import Path

import httpx
import pytest

from conftest import INTERNAL_KEY, real_model
from fake_nucleus import make_persona

pytestmark = [pytest.mark.asyncio, pytest.mark.live]

_EVIDENCE: list[str] = []


def show(test: str, lines: list[str]) -> None:
    """Print the evidence live (-s) AND keep it for REPORT-live.md."""
    block = [f"\n── {test} " + "─" * max(0, 60 - len(test))] + [f"  {l}" for l in lines]
    print("\n".join(block))
    _EVIDENCE.append("\n".join([f"## {test}"] + lines + [""]))


@pytest.fixture(scope="session", autouse=True)
def _write_live_report():
    yield
    if _EVIDENCE:
        path = Path(__file__).parent / "REPORT-live.md"
        head = ("# nexus-ai — REAL-model smoke report\n\n"
                "What each model actually said, per test. Regenerated by every "
                "`pytest tests/test_real_smoke.py --real` run. Git-ignored.\n\n")
        path.write_text(head + "\n".join(_EVIDENCE), encoding="utf-8")
        print(f"\nlive report written: {path}")


def _done(events: list[dict]) -> dict:
    [done] = [e for e in events if e["type"] == "message_done"]
    return done


async def _plain_reply(harness, provider: str, model_id: str | None = None) -> None:
    harness.nucleus.persona = make_persona(
        real_model(provider, model_id=model_id),
        system_prompt="You are a concise assistant. Answer in one short sentence.",
    )
    started = time.monotonic()
    events = await harness.trigger(harness.job(
        message="Say hello and name any one planet of the solar system."), timeout=120)
    secs = time.monotonic() - started

    types = [e["type"] for e in events]
    assert types[0] == "message_start" and types[-1] == "message_done"
    assert "message_delta" in types            # it streamed live
    assert "message_error" not in types
    done = _done(events)
    assert done["content"].strip() != ""       # a real answer arrived
    records = await harness.wait_for_usage(1)
    assert records[-1]["output_tokens"] > 0 and records[-1]["estimated"] is False

    show(f"live plain reply — {provider}", [
        f"model: {harness.nucleus.persona['model']['model_id']}  ({secs:.1f}s)",
        f"tokens: in={records[-1]['input_tokens']} out={records[-1]['output_tokens']}",
        f"reply: {done['content'][:300]}",
    ])


