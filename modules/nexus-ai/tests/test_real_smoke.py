async def test_live3_real_tool_roundtrip_grounded_fact(harness, tmp_path):
    """LIVE — the model really decides to call a tool, and the result grounds it.
    A file only the filesystem tool can see holds a code word; the model is
    asked for it. The reply containing the exact word PROVES the full loop:
    real model → tool call → our tool ran → result back → final answer.
    (A grounded fact is the one honest exact-match assert on a real model.)"""
    (tmp_path / "notes.txt").write_text("The secret code word for the launch is ZEBRA-42.")
    harness.nucleus.persona = make_persona(
        real_model("openai"),
        system_prompt="Use your tools to answer. Be brief.",
        capabilities=[{"id": "cap1", "name": "defaults",
                       "capability_config": {"filesystem": {"root_dir": str(tmp_path)}}}],
    )
    events = await harness.trigger(harness.job(
        message="Read the file notes.txt and tell me the exact code word."), timeout=180)

    done = _done(events)
    assert "ZEBRA-42" in done["content"]       # only a REAL tool call can know this
    assert done.get("used_tools")              # the engine recorded the tool ran

    show("live tool round-trip — openai + filesystem", [
        f"used tools: {done.get('used_tools')}",
        f"reply: {done['content'][:300]}",
    ])


async def test_live4_real_model_asks_before_answering(harness):
    """LIVE — a real model triggers the ask/pause road (item 5, for real).
    The persona's instructions demand asking which environment before any
    answer; the model calls ask_user → question_asked + message_paused, and
    the pause state lands on the (fake) nucleus. NOTE: this one depends on
    the model obeying an instruction — a rare failure here means the model
    answered without asking; rerun before suspecting the engine."""
    harness.nucleus.persona = make_persona(
        real_model("openai"),
        system_prompt=("Before answering ANY request you MUST call the ask_user tool "
                       "exactly once, asking which environment the user means, with "
                       "options ['dev', 'prod']. Never answer without asking first."),
    )
    events = await harness.trigger(harness.job(
        message="How do I restart the application server?"), timeout=120)

    types = [e["type"] for e in events]
    assert types[-1] == "message_paused"
    [q] = [e for e in events if e["type"] == "question_asked"]
    assert harness.nucleus.pause_posts         # the frozen state was saved

    show("live ask_user pause — openai", [
        f"model asked: {q['question'].get('question')}",
        f"options: {q['question'].get('options')}",
    ])


async def test_live5_model_check_good_and_bad_key(harness):
    """LIVE — /models/check against the real provider: a good key says ok,
    a garbage key is refused politely (ok=false with a worded error), and
    neither outcome is ever a 500 — the same contract nucleus's Add-model
    dialog depends on, now proven against the real wall clock."""
    good = real_model("openai")
    async with httpx.AsyncClient(timeout=60.0) as client:
        ok_resp = await client.post(
            f"{harness.app_url}/api/v1/models/check/",
            json={"provider": "openai", "model_id": good["model_id"],
                  "api_key": good["api_key"], "api_base": None},
            headers={"X-Internal-Key": INTERNAL_KEY})
        bad_resp = await client.post(
            f"{harness.app_url}/api/v1/models/check/",
            json={"provider": "openai", "model_id": good["model_id"],
                  "api_key": "sk-definitely-not-a-real-key", "api_base": None},
            headers={"X-Internal-Key": INTERNAL_KEY})
    assert ok_resp.status_code == 200 and bad_resp.status_code == 200
    ok, bad = ok_resp.json(), bad_resp.json()
    assert ok["ok"] is True and isinstance(ok["latency_ms"], int)
    assert bad["ok"] is False and bad.get("error")

    show("live model check — openai", [
        f"good key: ok={ok['ok']} latency={ok['latency_ms']}ms",
        f"bad key:  ok={bad['ok']} error_code={bad.get('error_code')}",
    ])
